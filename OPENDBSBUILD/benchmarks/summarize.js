// results.jsonl → median (and min–max) per database and metric → results.ts for the website
//   node summarize.js [results.jsonl] [out.ts]
const fs = require('fs');
const path = require('path');
const lines = fs.readFileSync(path.resolve(__dirname, process.argv[2] || 'results.jsonl'), 'utf8').trim().split('\n').map((l) => JSON.parse(l));
const med = (a) => { const s = [...a].sort((x, y) => x - y); return s.length % 2 ? s[(s.length - 1) / 2] : (s[s.length / 2 - 1] + s[s.length / 2]) / 2; };
const order = ['opendbs', 'postgres', 'mysql', 'mongo', 'sqlite'];
const METRICS = {
  bulkInsertRowsPerSec: (r) => r.bulkInsertRowsPerSec,
  indexBuildMs: (r) => r.indexBuildMs,
  pointRead: (r) => r.pointRead.ops,
  pointReadP50: (r) => r.pointRead.p50,
  pointReadP99: (r) => r.pointRead.p99,
  indexedQuery: (r) => r.indexedQuery.ops,
  indexedQueryP99: (r) => r.indexedQuery.p99,
  singleInsert: (r) => r.singleInsert.ops,
  singleInsertP99: (r) => r.singleInsert.p99,
  update: (r) => r.update.ops,
  updateP99: (r) => r.update.p99,
  groupByMs: (r) => r.groupByMs,
};
const out = [];
for (const key of order) {
  const runs = lines.filter((l) => l.key === key).map((l) => l.r);
  if (!runs.length) continue;
  const m = {};
  for (const [k, f] of Object.entries(METRICS)) {
    const v = runs.map(f);
    const round = (x) => (x >= 100 ? Math.round(x) : +x.toFixed(2));
    m[k] = { median: round(med(v)), min: round(Math.min(...v)), max: round(Math.max(...v)) };
  }
  out.push({ key, name: runs[0].db, runs: runs.length, rows: runs[0].rows, concurrency: runs[0].concurrency, m });
}
const ts = `// Generated by benchmarks/summarize.js from ${out[0]?.runs} runs per database. Do not edit by hand.
export interface Stat { median: number; min: number; max: number }
export type MetricKey = ${Object.keys(METRICS).map((k) => `'${k}'`).join(' | ')};
export interface BenchResult { key: string; name: string; runs: number; rows: number; concurrency: number; m: Record<MetricKey, Stat> }
export const BENCH_DATE = '${new Date().toISOString().slice(0, 10)}';
export const BENCH: BenchResult[] = ${JSON.stringify(out, null, 2)};
`;
fs.writeFileSync(process.argv[3] ? path.resolve(process.argv[3]) : path.join(__dirname, 'results.ts'), ts);
console.table(Object.fromEntries(out.map((r) => [r.name, Object.fromEntries(Object.entries(r.m).map(([k, s]) => [k, `${s.median} (${s.min}–${s.max})`]))])));
